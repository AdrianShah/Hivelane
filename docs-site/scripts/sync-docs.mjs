#!/usr/bin/env node
// Copy the repo's Markdown docs into src/content/docs/ as Starlight pages.
//
//   node scripts/sync-docs.mjs          (npm run sync; also the first step of
//                                         npm run dev and npm run build)
//
// The docs are written for GitHub, where they live next to the code, so each
// page gets:
//   - frontmatter: title from the first `# heading` (removed from the body,
//     since Starlight renders the title itself), a description from the first
//     paragraph, and an editUrl pointing at the real source file;
//   - links rewritten: a link to another synced file becomes a site link, and
//     a link to anything else in the repo (code, deploy configs) becomes a
//     GitHub link, so nothing 404s on the site.
// Sources listed in sources.mjs that do not exist are skipped with a note.
// Only files whose content changed are rewritten, and pages whose source is
// gone are deleted, so a running `astro dev` sees ordinary edits.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

import { BASE, BRANCH, OUT_DIR, REPO_PUBLIC, REPO_ROOT, REPO_URL, SITE_PAGES, SITE_ROOT, resolvePages, sourceOf } from '../sources.mjs';

const GENERATED_NOTE = 'Generated by docs-site/scripts/sync-docs.mjs';
// '/docs' and '/docs/' alike; '' or '/' for a site at the domain root.
const PREFIX = BASE.replace(/\/+$/, '');
const BLOB = `${REPO_URL}/blob/${BRANCH}/`;
const TREE = `${REPO_URL}/tree/${BRANCH}/`;
const RAW = `https://raw.githubusercontent.com/${REPO_URL.split('github.com/')[1]}/${BRANCH}/`;
const FENCE = /^\s{0,3}(`{3,}|~{3,})/;

// --- Markdown helpers ---------------------------------------------------------

/** Lines tagged with whether they sit inside a fenced code block. */
function scanLines(text) {
  const out = [];
  let fence = null;
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(FENCE);
    if (fence) {
      out.push({ line, code: true });
      if (match && match[1][0] === fence[0] && match[1].length >= fence.length) fence = null;
    } else if (match) {
      fence = match[1];
      out.push({ line, code: true });
    } else {
      out.push({ line, code: false });
    }
  }
  return out;
}

/** Plain text of an inline Markdown snippet (for titles and descriptions). */
function plain(text) {
  return text
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/(\*\*|__)(.*?)\1/g, '$2')
    .replace(/(^|\W)[*_](\S(?:.*?\S)?)[*_](?=\W|$)/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

/** First plain paragraph of the body, if the body opens with one. */
function firstParagraph(lines) {
  const para = [];
  for (const { line, code } of lines) {
    if (code) break;
    if (!line.trim()) {
      if (para.length) break;
      continue;
    }
    if (!para.length && /^\s*([#|>!<-]|[*+]\s|\d+[.)]\s|---)/.test(line)) return '';
    para.push(line.trim());
  }
  const text = plain(para.join(' '));
  if (text.length <= 200) return text;
  const cut = text.slice(0, 200);
  return `${cut.slice(0, cut.lastIndexOf(' '))}…`;
}

/** Whole file: the first `# heading` is the title and leaves the body. */
function splitFile(text) {
  const lines = scanLines(text);
  const index = lines.findIndex(({ line, code }) => !code && /^#\s+\S/.test(line));
  if (index === -1) return { title: null, lines };
  return { title: plain(lines[index].line.replace(/^#\s+/, '').replace(/\s+#*\s*$/, '')), lines: lines.slice(index + 1) };
}

/** One `## heading` section, with its sub-headings promoted one level. */
function extractSection(text, heading) {
  const lines = scanLines(text);
  const isH2 = ({ line, code }) => !code && /^##\s+\S/.test(line);
  const start = lines.findIndex((entry) => isH2(entry) && plain(entry.line.slice(3)) === heading);
  if (start === -1) return null;
  // The section ends at the next `## ` heading or at a `---` rule, which the
  // README uses between sections (and before stray paragraphs that belong to
  // no section).
  const isRule = ({ line, code }, i) => !code && /^\s{0,3}(-{3,}|\*{3,}|_{3,})\s*$/.test(line) && !lines[i - 1]?.line.trim();
  let end = lines.findIndex((entry, i) => i > start && (isH2(entry) || isRule(entry, i)));
  if (end === -1) end = lines.length;
  const body = lines.slice(start + 1, end).map((entry) =>
    !entry.code && /^#{3,6}\s/.test(entry.line) ? { ...entry, line: entry.line.slice(1) } : entry,
  );
  while (body.length && !body.at(-1).line.trim()) body.pop();
  return body;
}

// --- links ---------------------------------------------------------------------

function pageUrl(slug, fragment = '') {
  return slug === 'index' ? `${PREFIX}/${fragment}` : `${PREFIX}/${slug}/${fragment}`;
}

/**
 * Where a link in `source` (a repo-relative path) should point on the site.
 * `bySource` maps repo paths to slugs. `section` marks a page cut out of a
 * larger file, whose same-page anchors may point outside the cut.
 */
function rewriteTarget(target, { source, section, bySource, image }) {
  const [path, hash] = splitHash(target);
  if (!path) {
    // Same-page anchor: fine for a whole file; for a section it may name a
    // heading that was left behind, so send it to the full file on GitHub.
    return section ? `${BLOB}${source}${hash}` : target;
  }
  const github = path.startsWith(BLOB) ? path.slice(BLOB.length) : null;
  if (github !== null) {
    const slug = bySource.get(github);
    return slug ? pageUrl(slug, hash) : target;
  }
  if (/^[a-z][a-z0-9+.-]*:/i.test(path) || path.startsWith('//') || path.startsWith('/')) return target;

  const resolved = posix.normalize(posix.join(posix.dirname(source), decodeURI(path)));
  if (resolved.startsWith('..')) return target;
  const slug = bySource.get(resolved);
  if (slug && !image) return pageUrl(slug, hash);
  if (image) return `${RAW}${encodeURI(resolved)}`;
  const full = join(REPO_ROOT, ...resolved.split('/'));
  const isDir = existsSync(full) && statSync(full).isDirectory();
  return `${isDir ? TREE : BLOB}${encodeURI(resolved).replace(/\/$/, '')}${hash}`;
}

function splitHash(target) {
  const at = target.indexOf('#');
  return at === -1 ? [target, ''] : [target.slice(0, at), target.slice(at)];
}

const INLINE_LINK = /(!?)\[((?:[^\[\]]|\[[^\]]*\])*)\]\(\s*(<[^>]*>|[^\s)]+)(\s+(?:"[^"]*"|'[^']*'))?\s*\)/g;
const REFERENCE_DEF = /^(\s{0,3}\[[^\]]+\]:\s*)(<[^>]*>|\S+)(.*)$/;

/** Rewrite the links on one non-code line, leaving inline code untouched. */
function rewriteLine(line, context) {
  const def = line.match(REFERENCE_DEF);
  if (def) {
    const target = def[2].replace(/^<|>$/g, '');
    return `${def[1]}${rewriteTarget(target, { ...context, image: false })}${def[3]}`;
  }
  const spans = [];
  const masked = line.replace(/(`+)[^`]*?\1/g, (span) => {
    spans.push(span);
    return `\u0000${spans.length - 1}\u0000`;
  });
  const linked = masked.replace(INLINE_LINK, (all, bang, text, rawTarget, title = '') => {
    const target = rawTarget.replace(/^<|>$/g, '');
    const next = rewriteTarget(target, { ...context, image: bang === '!' });
    return `${bang}[${text}](${next}${title})`;
  });
  return linked.replace(/\u0000(\d+)\u0000/g, (_, i) => spans[Number(i)]);
}

// --- pages ---------------------------------------------------------------------

function frontmatter(fields) {
  // JSON strings are valid YAML double-quoted scalars, so this escapes safely.
  const lines = Object.entries(fields)
    .filter(([, value]) => value !== undefined && value !== '')
    .map(([key, value]) => `${key}: ${JSON.stringify(value)}`);
  return `---\n${lines.join('\n')}\n---\n`;
}

function buildPage(item, bySource) {
  const source = sourceOf(item);
  const text = readFileSync(join(REPO_ROOT, ...source.split('/')), 'utf8').replace(/^﻿/, '');
  let title;
  let lines;
  if (item.section) {
    lines = extractSection(text, item.section.heading);
    if (!lines) throw new Error(`${source} has no "## ${item.section.heading}" section (needed for ${item.slug})`);
    title = item.title ?? item.section.heading;
  } else {
    ({ title, lines } = splitFile(text));
    title = item.title ?? title ?? item.slug;
  }
  const context = { source, section: Boolean(item.section), bySource };
  const body = lines.map(({ line, code }) => (code ? line : rewriteLine(line, context))).join('\n');
  const where = item.section ? `the "${item.section.heading}" section of ${source}` : source;
  return (
    frontmatter({
      title,
      description: item.description ?? firstParagraph(lines),
      editUrl: REPO_PUBLIC ? `${REPO_URL}/edit/${BRANCH}/${source}` : undefined,
    }) +
    `\n<!-- ${GENERATED_NOTE} from ${where}. Edit that file, not this one. -->\n` +
    `${body.replace(/^\s*\n/, '\n').trimEnd()}\n`
  );
}

function buildSitePage(item) {
  const text = readFileSync(join(SITE_ROOT, item.page), 'utf8');
  return text.replaceAll('{{BASE}}', PREFIX);
}

function outputPath(item) {
  const ext = item.page ? posix.extname(item.page) : '.md';
  return join(OUT_DIR, ...`${item.slug}${ext}`.split('/'));
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full) : [full];
  });
}

export function syncDocs({ log = console.log } = {}) {
  const { pages, missing } = resolvePages();
  const bySource = new Map(pages.filter((page) => !page.section).map((page) => [sourceOf(page), page.slug]));
  const wanted = new Map();
  for (const item of pages) wanted.set(outputPath(item), buildPage(item, bySource));
  for (const item of SITE_PAGES) wanted.set(outputPath(item), buildSitePage(item));

  let written = 0;
  for (const [path, content] of wanted) {
    if (existsSync(path) && readFileSync(path, 'utf8') === content) continue;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    written += 1;
  }
  let removed = 0;
  for (const path of listFiles(OUT_DIR)) {
    if (!wanted.has(path)) {
      rmSync(path);
      removed += 1;
    }
  }
  for (const source of missing) log(`sync-docs: skipped ${source} (not found)`);
  const shown = relative(SITE_ROOT, OUT_DIR).split(sep).join('/');
  log(`sync-docs: ${wanted.size} page(s) in ${shown} (${written} written, ${removed} removed)`);
  return { pages: wanted.size, written, removed, missing };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  syncDocs();
}
