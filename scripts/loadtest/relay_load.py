REPO = Path(__file__).resolve().parents[2]
P95_TARGET_MS = 50.0
DIFF = "".join(f"+    line {i}: value = compute(value, {i})  # padding padding\n" for i in range(36))  # ~2 KB


# --- relay process ---------------------------------------------------------------


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def relay_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = dict(os.environ)
    env.update(
        SYNERGO_ENV="development",
        ROOM_CREATE_LIMIT="0",
        WS_ATTEMPT_LIMIT="0",
        ROOM_MESSAGE_LIMIT="0",
        SYNERGO_MAX_ROOMS="0",
        SYNERGO_MAX_MEMBERS="0",
        SYNERGO_STATIC_DIR="",
        PYTHONUNBUFFERED="1",
    )
    env.pop("GEMINI_API_KEY", None)
    env.pop("SYNERGO_STATE_PATH", None)
    env.pop("SYNERGO_REDIS_URL", None)
    env.update(extra or {})
    return env


def start_relay(port: int, log_path: Path, python: str, extra_env: dict[str, str] | None = None):
    log = open(log_path, "ab")
    proc = subprocess.Popen(
        [python, "-m", "uvicorn", "server.main:app", "--host", "127.0.0.1", "--port", str(port),
         "--log-level", "warning", "--ws-max-size", str(1 << 20)],
        cwd=REPO, env=relay_env(extra_env), stdout=log, stderr=subprocess.STDOUT,
    )
    deadline = time.time() + 30
    while time.time() < deadline:
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=1).read()
            return proc
        except Exception:
            if proc.poll() is not None:
                raise RuntimeError(f"relay exited: see {log_path}")
            time.sleep(0.2)
    proc.kill()
    raise RuntimeError("relay did not start")


def create_room(port: int) -> str:
    req = urllib.request.Request(f"http://127.0.0.1:{port}/rooms", data=b"", method="POST")
    with urllib.request.urlopen(req, timeout=10) as resp:
        return json.loads(resp.read())["room_id"]


class ProcSampler:
    """CPU seconds and RSS of the relay process."""

    def __init__(self, pid: int) -> None:
        self.pid = pid
        try:
            import psutil  # type: ignore

            proc = psutil.Process(pid)
            # A venv's python.exe on Windows is a launcher; the relay is its child.
            kids = proc.children(recursive=True)
            self._ps = max(kids, key=lambda k: k.memory_info().rss) if kids else proc
        except Exception:
            self._ps = None
            if sys.platform == "win32":
                out = subprocess.run(
                    ["powershell", "-NoProfile", "-Command",
                     f"(Get-CimInstance Win32_Process -Filter 'ParentProcessId={pid}').ProcessId"],
                    capture_output=True, text=True, timeout=20,
                ).stdout.split()
                if out:
                    self.pid = int(out[0])

    def sample(self) -> tuple[float, int]:
        if self._ps is not None:
            t = self._ps.cpu_times()
            return t.user + t.system, self._ps.memory_info().rss
        if sys.platform == "win32":
            out = subprocess.run(
                ["powershell", "-NoProfile", "-Command",
                 f"$p=Get-Process -Id {self.pid}; \"$($p.TotalProcessorTime.TotalSeconds) $($p.WorkingSet64)\""],
                capture_output=True, text=True, timeout=20,
            ).stdout.split()
            return float(out[0].replace(",", ".")), int(out[1])
        stat = Path(f"/proc/{self.pid}/stat").read_text().split()
        tick = os.sysconf("SC_CLK_TCK")
        rss = int(Path(f"/proc/{self.pid}/statm").read_text().split()[1]) * os.sysconf("SC_PAGE_SIZE")
        return (int(stat[13]) + int(stat[14])) / tick, rss


# --- load worker -------------------------------------------------------------------


@dataclass
class WorkerResult:
    rtt_ms: list[float] = field(default_factory=list)
    fanout_ms: list[float] = field(default_factory=list)
    sent: int = 0
    received: int = 0
    connect_errors: int = 0
    disconnects: int = 0
    timeouts: int = 0
    decisions: dict[str, int] = field(default_factory=dict)


async def run_worker_async(port, rooms, members, spectators, rate, ramp_s, start_at, window_s):
    import websockets

    res = WorkerResult()
    sent_marks: dict[str, float] = {}
    measuring = {"on": False}
    stop = asyncio.Event()
    base = f"ws://127.0.0.1:{port}/ws/"

    async def reader(ws, spectator: bool, pending: dict[str, float]):
        try:
            async for raw in ws:
                now = time.perf_counter()
                res.received += 1
                msg = json.loads(raw)
                kind = msg.get("type")
                if kind == "edit_check_response":
                    t0 = pending.pop(msg.get("request_id"), None)
                    if t0 is not None and measuring["on"]:
                        res.rtt_ms.append((now - t0) * 1000)
                        d = msg.get("decision", "?")
                        res.decisions[d] = res.decisions.get(d, 0) + 1
                elif kind == "synergo_feed" and spectator and measuring["on"]:
                    for ev in msg.get("events", ()):
                        if ev.get("type") == "activity_update":
                            mark = (ev.get("prompt") or " ").split(" ", 1)[0]
                            t0 = sent_marks.get(mark)
                            if t0 is not None:
                                res.fanout_ms.append((now - t0) * 1000)
        except Exception:
            if not stop.is_set():
                res.disconnects += 1

    async def connect(code: str):
        for attempt in range(3):
            try:
                return await websockets.connect(base + code, max_size=None, open_timeout=30, ping_interval=None)
            except Exception:
                await asyncio.sleep(0.5 + attempt)
        res.connect_errors += 1
        return None

    async def spectator(code: str, delay: float):
        await asyncio.sleep(delay)
        ws = await connect(code)
        if ws is None:
            return
        await ws.send(json.dumps({"type": "join"}))
        task = asyncio.create_task(reader(ws, True, {}))
        await stop.wait()
        await ws.close()
        task.cancel()

    async def member(code: str, idx: int, delay: float):
        await asyncio.sleep(delay)
        ws = await connect(code)
        if ws is None:
            return
        name = f"m{idx}"
        await ws.send(json.dumps({"type": "join", "name": name, "agent": "claude-code", "protocol_version": 1}))
        pending: dict[str, float] = {}
        task = asyncio.create_task(reader(ws, False, pending))
        rnd = random.Random(hash((code, idx)))
        n = 0
        # Members start sending once everyone is in, spread over one interval.
        await asyncio.sleep(max(0.0, start_at - time.time()) + rnd.random() / rate)
        try:
            while not stop.is_set():
                n += 1
                path = f"src/mod{rnd.randrange(20)}.py"
                if n % 20 == 0:
                    frame = {"type": "plan", "user_id": name, "summary": "refactor the parser",
                             "files": [path, f"src/mod{rnd.randrange(20)}.py"], "symbols": ["parse"]}
                elif n % 10 == 0:
                    frame = {"type": "intent", "user_id": name, "prompt": f"fix the bug in mod{rnd.randrange(20)}.py"}
                elif n % 2 == 1:
                    rid = uuid.uuid4().hex
                    pending[rid] = time.perf_counter()
                    frame = {"type": "edit_check", "request_id": rid, "file_path": path,
                             "symbols": [f"fn{rnd.randrange(8)}"], "line_ranges": [[10, 30]]}
                else:
                    mark = f"lt:{uuid.uuid4().hex}"
                    sent_marks[mark] = time.perf_counter()
                    frame = {"type": "activity", "user_id": name, "prompt": mark + " make the change",
                             "changes": [{"file_path": path, "diff": DIFF, "symbols": [f"fn{rnd.randrange(8)}"],
                                          "line_ranges": [[10, 46]]}]}
                await ws.send(json.dumps(frame))
                res.sent += 1
                now = time.perf_counter()
                for rid, t0 in list(pending.items()):
                    if now - t0 > 5.0:
                        pending.pop(rid, None)
                        if measuring["on"]:
                            res.timeouts += 1
                await asyncio.sleep(1.0 / rate)
        except Exception:
            if not stop.is_set():
                res.disconnects += 1
        await ws.close()
        task.cancel()

    tasks = []
    total = len(rooms) * (members + spectators)
    i = 0
    for code in rooms:
        for s in range(spectators):
            tasks.append(asyncio.create_task(spectator(code, ramp_s * i / max(1, total))))
            i += 1
        for m in range(members):
            tasks.append(asyncio.create_task(member(code, m, ramp_s * i / max(1, total))))
            i += 1
    await asyncio.sleep(max(0.0, start_at - time.time()) + 2.0)  # warm-up after start
    measuring["on"] = True
    await asyncio.sleep(window_s)
    measuring["on"] = False
    stop.set()
    await asyncio.wait(tasks, timeout=10)
    return res


def run_worker(args, out_q):
    if sys.platform == "win32":
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    res = asyncio.run(run_worker_async(*args))
    out_q.put(asdict(res))


# --- one step --------------------------------------------------------------------------


def pct(values: list[float], p: float) -> float:
    if not values:
        return float("nan")
    values = sorted(values)
    k = min(len(values) - 1, max(0, int(round(p / 100 * (len(values) - 1)))))
    return values[k]


def run_step(name, rooms, members, spectators, rate, window_s, python, out_dir, workers, history_hours=0):
    port = free_port()
    # The relay logs every message at info level; keep that out of the results.
    proc = start_relay(port, Path(tempfile.gettempdir()) / "synergo-relay-load.log", python)
    try:
        codes = [create_room(port) for _ in range(rooms)]
        sockets = rooms * (members + spectators)
        ramp_s = min(20.0, max(1.0, sockets / 150))
        start_at = time.time() + ramp_s + 1.0
        nworkers = max(1, min(workers, rooms if rooms > 1 else 1))
        if rooms == 1:
            nworkers = 1
        q = mp.Queue()
        chunks = [codes[i::nworkers] for i in range(nworkers)]
        procs = [mp.Process(target=run_worker, args=((port, c, members, spectators, rate, ramp_s, start_at, window_s), q))
                 for c in chunks if c]
        for p in procs:
            p.start()
        sampler = ProcSampler(proc.pid)
        time.sleep(max(0.0, start_at - time.time()) + 2.0)
        cpu0, rss0 = sampler.sample()
        t0 = time.perf_counter()
        rss_peak = rss0
        while time.perf_counter() - t0 < window_s - 1:
            time.sleep(min(5.0, window_s / 3))
            _, rss = sampler.sample()
            rss_peak = max(rss_peak, rss)
        cpu1, rss1 = sampler.sample()
        cpu_pct = (cpu1 - cpu0) / (time.perf_counter() - t0) * 100
        results = [q.get(timeout=window_s + 120) for _ in procs]
        for p in procs:
            p.join(timeout=30)
        merged = WorkerResult()
        for r in results:
            merged.rtt_ms += r["rtt_ms"]
            merged.fanout_ms += r["fanout_ms"]
            for k in ("sent", "received", "connect_errors", "disconnects", "timeouts"):
                setattr(merged, k, getattr(merged, k) + r[k])
            for k, v in r["decisions"].items():
                merged.decisions[k] = merged.decisions.get(k, 0) + v
        alive = proc.poll() is None
    finally:
        proc.kill()
        proc.wait()
    total_window_s = window_s + 2.0 + 3.0  # roughly the sending period
    row = {
        "step": name, "rooms": rooms, "members_per_room": members, "spectators_per_room": spectators,
        "total_members": rooms * members, "total_sockets": rooms * (members + spectators),
        "rate_per_member": rate, "offered_msgs_per_s": rooms * members * rate,
        "edit_checks": len(merged.rtt_ms),
        "rtt_p50_ms": round(pct(merged.rtt_ms, 50), 2), "rtt_p95_ms": round(pct(merged.rtt_ms, 95), 2),
        "rtt_p99_ms": round(pct(merged.rtt_ms, 99), 2),
        "fanout_samples": len(merged.fanout_ms),
        "fanout_p50_ms": round(pct(merged.fanout_ms, 50), 1), "fanout_p95_ms": round(pct(merged.fanout_ms, 95), 1),
        "fanout_p99_ms": round(pct(merged.fanout_ms, 99), 1),
        "relay_cpu_pct": round(cpu_pct, 1), "relay_rss_mb": round(rss_peak / 2**20, 1),
        "relay_rss_start_mb": round(rss0 / 2**20, 1),
        "frames_received_per_s": round(merged.received / total_window_s, 0),
        "connect_errors": merged.connect_errors, "disconnects": merged.disconnects,
        "timeouts": merged.timeouts, "relay_alive": alive,
        "decisions": json.dumps(merged.decisions, sort_keys=True),
    }
    row["ok"] = bool(row["rtt_p95_ms"] < P95_TARGET_MS and not (merged.connect_errors or merged.disconnects or merged.timeouts))
    return row


SWEEPS = {
    # name: list of (step, rooms, members, spectators)
    "quick": [("smoke", 2, 3, 1)],
    "rooms": [(f"rooms-{n}", n, 3, 1) for n in (1, 10, 50, 100, 250, 500)],
    "room-size": [(f"room-size-{m}", 1, m, 2) for m in (2, 6, 12, 25, 50, 100)],
    "members": [(f"members-{n * 6}", n, 6, 1) for n in (5, 10, 20, 40, 80, 160)],
}
SWEEPS["full"] = SWEEPS["rooms"] + SWEEPS["room-size"] + SWEEPS["members"]


def machine_info() -> dict:
    info = {"platform": platform.platform(), "python": sys.version.split()[0], "cpu_count": os.cpu_count(),
            "processor": platform.processor()}
    if sys.platform == "win32":
        try:
            out = subprocess.run(["powershell", "-NoProfile", "-Command",
                                  "(Get-CimInstance Win32_Processor).Name; (Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory"],
                                 capture_output=True, text=True, timeout=30).stdout.split("\n")
            info["cpu_model"] = out[0].strip()
            info["ram_gb"] = round(int(out[1].strip()) / 2**30, 1)
        except Exception:
            pass
    return info


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sweep", choices=sorted(SWEEPS), help="named sweep (default: one custom step)")
    ap.add_argument("--rooms", type=int, default=2)
    ap.add_argument("--members", type=int, default=3)
    ap.add_argument("--spectators", type=int, default=1)
    ap.add_argument("--rate", type=float, default=2.0, help="messages/s per member (default 2)")
    ap.add_argument("--window", type=float, default=15.0, help="measurement seconds per step")
    ap.add_argument("--workers", type=int, default=4, help="load-generator processes")
    ap.add_argument("--python", default=sys.executable, help="interpreter that runs the relay")
    ap.add_argument("--out", default=str(REPO / "benchmarks" / "load"))
    ap.add_argument("--stop-after-failures", type=int, default=2,
                    help="skip the rest of a sweep after this many failing steps in a row")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    steps = SWEEPS[args.sweep] if args.sweep else [("custom", args.rooms, args.members, args.spectators)]
    tag = args.sweep or "custom"
    rows = []
    fails = 0
    prefix = None
    for name, rooms, members, spectators in steps:
        family = name.split("-")[0]
        if family != prefix:
            prefix, fails = family, 0
        if fails >= args.stop_after_failures:
            print(f"skip {name} (sweep past its knee)", flush=True)
            continue
        started = time.time()
        row = run_step(name, rooms, members, spectators, args.rate, args.window, args.python, out, args.workers)
        row["step_seconds"] = round(time.time() - started, 1)
        rows.append(row)
        fails = 0 if row["ok"] else fails + 1
        print(json.dumps(row), flush=True)
    with open(out / f"relay_load_{tag}.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (out / f"relay_load_{tag}.json").write_text(json.dumps({"machine": machine_info(), "rate_per_member": args.rate,
                                                            "window_s": args.window, "steps": rows}, indent=2))
    print(f"\n{'step':<16}{'members':>8}{'socks':>7}{'msg/s':>7}{'p50':>8}{'p95':>8}{'p99':>8}{'fan p95':>9}{'cpu%':>7}{'rss MB':>8}  ok")
    for r in rows:
        print(f"{r['step']:<16}{r['total_members']:>8}{r['total_sockets']:>7}{r['offered_msgs_per_s']:>7.0f}"
              f"{r['rtt_p50_ms']:>8}{r['rtt_p95_ms']:>8}{r['rtt_p99_ms']:>8}{r['fanout_p95_ms']:>9}"
              f"{r['relay_cpu_pct']:>7}{r['relay_rss_mb']:>8}  {r['ok']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
