"""Capacity / load test for one relay process.

Starts a relay (`uvicorn server.main:app`) in a subprocess on a free port with
every capacity and rate limit switched off, then runs a sweep of steps. Each
step: N rooms x M members per room x K spectators per room. Every member
sends a realistic mix at R messages/s (edit_check and activity with a ~2 KB
diff alternating, an intent every 10th message, a plan every 20th), over a
pool of 20 files per room so warns/blocks (and their broadcasts) happen.

Measured per step, inside a fixed window after every socket has joined:
- edit_check round trip (send -> edit_check_response), p50/p95/p99;
- broadcast fan-out latency (activity sent -> activity_update received by a
  spectator). It includes the relay's 0.5 s feed debounce
  (room.BROADCAST_FLUSH_SECONDS), so ~250 ms average is the floor;
- relay CPU % (of one core) and RSS (psutil if importable, else PowerShell
  Get-Process on Windows or /proc on Linux);
- errors: failed connects, disconnects, edit_checks unanswered within 5 s.

Load is generated by several worker processes; a room's members and
spectators always live in the same worker so latencies use one clock.

No dependencies beyond the relay's own (`websockets`); psutil is optional.

    python scripts/loadtest/relay_load.py --sweep quick
    python scripts/loadtest/relay_load.py --sweep full --out benchmarks/load
    python scripts/loadtest/relay_load.py --rooms 10 --members 6 --spectators 1 --rate 2
"""

